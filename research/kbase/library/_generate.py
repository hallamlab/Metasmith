#!/usr/bin/env python3
"""The KBase app catalog, as a metasmith library, and the generator that emits it.

`research/kbase/catalog/apps.jsonl` is 493 KBase app specs distilled to their
typed contract. This module is the port of that contract into a typed graph: it
writes `data_types/kbase.yml`, `data_types/env.yml`, every `resources/env/*.env`
and every stub transform under `transforms/kbase/`, plus the conversion ledger.

Following `src/metasmith_libraries/transforms/aspire/_generate.py`, which does
the same job for a Nextflow pipeline. The table here is machine-built rather
than hand-written, so the lifecycle rule is the same but sharper: the moment a
stub body becomes a real protocol, regenerating clobbers it.

Four things the port does to the source, each recorded per app in the ledger:

* **A report is a product.** 207 of the 235 active apps declare no typed output
  parameter and emit only a `KBaseReport`, named in the service output mapping
  rather than by a parameter flag. Dropping them for want of an
  `is_output_name` would discard most of the catalog, so they produce
  `kbase::report`.
* **A parameter accepting several workspace types becomes a union type.** 25% of
  typed parameters accept more than one. A union is one bare property token that
  every member type also carries, so membership is structural subtyping and
  needs no `extends:`.
* **An output accepting several types becomes a product group**, one branch per
  type. Past `MAX_OUTPUT_BRANCHES` the app is a generic object shuffler rather
  than a workflow step, and is dropped rather than modelled. The cap is 8 because
  4 was wrong: `kb_cutadapt/remove_adapters` declares 6 output types because an
  adapter trimmer preserves whatever read type it was given, and dropping it
  blocked 18 of the 623 curated workflows. The one app the cap is actually for
  declares 58.
* **Lineage KBase does not have is added.** Every app requires a study and a
  sample, and every typed input descends from the sample. Without that the
  planner has no ancestry to tell two Genomes apart.

Run it:

    python research/kbase/library/_generate.py           # write everything
    python research/kbase/library/_generate.py --lint    # checks only
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
CATALOG = REPO / "research" / "kbase" / "catalog"
AGG = REPO / "data" / "kbase" / "aggregate"

TYPES_YML = HERE / "data_types" / "kbase.yml"
ENV_YML = HERE / "data_types" / "env.yml"
ENV_DIR = HERE / "resources" / "env"
XFORM_DIR = HERE / "transforms" / "kbase"

MAX_OUTPUT_BRANCHES = 8

BANNER = "# GENERATED by research/kbase/library/_generate.py -- do not edit by hand.\n"

RESOURCES = {
    "assembly": (16, 32, 24),
    "annotation": (8, 16, 12),
    "comparative_genomics": (8, 16, 8),
    "communities": (8, 16, 12),
    "metabolic_modeling": (4, 8, 4),
    "expression": (4, 8, 4),
    "reads": (4, 8, 6),
    "sequence": (4, 8, 4),
    "upload": (2, 4, 4),
    "util": (2, 4, 2),
}
DEFAULT_RESOURCES = (4, 8, 4)


def load():
    apps = [json.loads(l) for l in (CATALOG / "apps.jsonl").read_text().splitlines() if l]
    types = {t["ws_type"]: t for t in
             (json.loads(l) for l in (CATALOG / "types.jsonl").read_text().splitlines() if l)}
    modules = json.loads((AGG / "modules.json").read_text())
    images = json.loads((AGG / "images.json").read_text())
    return apps, types, modules, images


def ws_split(ws: str):
    """(module, name) for a KBase type reference, or None when it is not one."""
    if "." not in ws: return None
    module, _, name = ws.partition(".")
    if not module or not name or "." in name: return None
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", module): return None
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name): return None
    return module, name


def type_name(ws: str) -> str | None:
    parts = ws_split(ws)
    return f"{parts[0]}_{parts[1]}" if parts else None


KEYSTONES = {
    "study": "one KBase analysis; the grouping parent every sample descends from",
    "sample": "one input sample within a KBase study",
    "report": "a KBaseReport: the html/file summary a KBase app emits beside its typed products",
}


def build_unions(apps) -> tuple[dict, dict]:
    """union type name -> (token, members); and ws type -> set of tokens it carries."""
    sets = set()
    for a in apps:
        for e in a["inputs"] + a["outputs"]:
            members = tuple(sorted(t for t in e["ws_types"] if type_name(t)))
            if len(members) > 1: sets.add(members)
    unions, tokens = {}, collections.defaultdict(set)
    for i, members in enumerate(sorted(sets), start=1):
        name = f"accepts_{i:02d}"
        token = f"kbase-union-{i:02d}"
        unions[name] = (token, members)
        for m in members: tokens[m].add(token)
    return unions, dict(tokens)


def referenced_types(apps) -> list[str]:
    seen = set()
    for a in apps:
        for e in a["inputs"] + a["outputs"]:
            seen.update(t for t in e["ws_types"] if type_name(t))
    return sorted(seen)


def _yaml_str(s: str) -> str:
    return json.dumps(" ".join(str(s).split()))


def write_types(apps, types) -> tuple[int, dict, dict]:
    unions, tokens = build_unions(apps)
    concrete = referenced_types(apps)

    out = [
        BANNER,
        "# The KBase workspace type graph.\n#\n",
        "# Every type carries its module and name as matched properties, so no two\n",
        "# collapse into one node and none silently satisfies another. A union is a\n",
        "# bare token its members also carry, which is why nothing here uses\n",
        "# `extends:` -- the closure is computed at generation time instead.\n",
        "types:\n",
        "# -- lineage keystones and the report product --\n",
    ]
    for name, desc in KEYSTONES.items():
        out.append(f"  {name}:\n    properties:\n      _:\n      - {_yaml_str(desc)}\n")
        out.append(f"      kbase_role: {name}\n")

    out.append("# -- parameter unions: a token every member type also carries --\n")
    out.append("# A union carries its token and NOTHING else. `_` is a matched property, not\n")
    out.append("# a comment, so a description here would be a property no member has, and\n")
    out.append("# subtyping -- which is subset-of-properties -- would silently never hold.\n")
    for name, (token, members) in unions.items():
        out.append(f"  # {name}: any of {', '.join(members)}\n")
        out.append(f"  {name}:\n    properties:\n      _:\n      - {token}\n")

    out.append("# -- the workspace types themselves --\n")
    n = 0
    for ws in concrete:
        module, name = ws_split(ws)
        rec = types.get(ws) or {}
        desc = (rec.get("description") or "").strip()
        desc = " ".join(desc.split())[:200] or f"KBase workspace type {ws}"
        out.append(f"  {type_name(ws)}:\n    properties:\n      _:\n")
        out.append(f"      - {_yaml_str(desc)}\n")
        for token in sorted(tokens.get(ws, ())):
            out.append(f"      - {token}\n")
        out.append(f"      ws_module: {module}\n      ws_name: {name}\n")
        if rec.get("status") and rec["status"] != "resolved":
            out.append(f"      # not in the type registry: {rec['status']}\n")
        n += 1

    TYPES_YML.parent.mkdir(parents=True, exist_ok=True)
    TYPES_YML.write_text("".join(out))
    return n + len(unions) + len(KEYSTONES), unions, tokens


def env_type_name(module: str) -> str:
    return f"{module}.env"


def write_envs(apps, modules, images) -> int:
    used = sorted({a["module"] for a in apps if a["module"]})
    out = [
        BANNER,
        "# One environment per KBase app module. Container arm only: KBase ships\n",
        "# images and no conda recipes, and an arm that has never been run answers\n",
        "# 'can this tool run without a container' wrongly.\n",
        "types:\n",
        "  env:\n    properties:\n",
        "      _: generic tool environment; see resources/env/*.env\n",
    ]
    ENV_DIR.mkdir(parents=True, exist_ok=True)
    written = 0
    for module in used:
        m = modules.get(module) or {}
        img = m.get("docker_img_name")
        if not img: continue
        digest = (images.get(img) or {}).get("digest")
        out.append(f"  {env_type_name(module)}:\n    extends: env\n    properties:\n")
        out.append(f"      provides:\n      - {module}\n")

        pinned = f"{img.split(':')[0]}@{digest}" if digest else img
        (ENV_DIR / env_type_name(module)).write_text(
            f"# KBase module {module} v{m.get('version')}, built from\n"
            f"# {m.get('git_url')} at {m.get('git_commit_hash')}.\n"
            f"# The tag is {img.split(':', 1)[1] if ':' in img else img} -- KBase embeds the\n"
            f"# module's git commit in the tag, so the tag is already immutable by\n"
            f"# construction. The digest below is that same image, resolved from the\n"
            f"# registry on 2026-09-04, because a digest is what this library pins by.\n"
            f"container: docker://{pinned}\n"
        )
        written += 1
    ENV_YML.write_text("".join(out))
    return written


def _module_of(app) -> str | None:
    return app["module"]


def _resources(app):
    for c in app["categories"]:
        if c in RESOURCES: return RESOURCES[c]
    return DEFAULT_RESOURCES


def _var(param_id: str, used: set) -> str:
    v = re.sub(r"\W", "_", param_id).strip("_").lower() or "p"
    if re.match(r"^\d", v): v = "p_" + v
    if v in {"lib", "model", "protocol", "context", "study", "sample", "env", "report"}:
        v = v + "_"
    base, i = v, 2
    while v in used:
        v = f"{base}{i}"; i += 1
    used.add(v)
    return v


def plan_app(app, unions_by_members) -> tuple[dict | None, str]:
    """Decide how one app becomes a transform, or why it does not."""
    if app["output_channel"] == "none":
        return None, "no_product"

    outs = []
    for e in app["outputs"]:
        members = tuple(sorted(t for t in e["ws_types"] if type_name(t)))
        if not members: continue
        if len(members) > MAX_OUTPUT_BRANCHES:
            return None, "polymorphic_output"
        outs.append((e, members))

    # An optional KBase parameter must NOT become a metasmith requirement.
    # A requirement is mandatory, so modelling `media_id` or `expseries_id` as one
    # makes run_flux_balance_analysis demand an expression matrix nobody has, and
    # the workflow that 45 narratives actually ran stops having a plan.
    ins, skipped_optional = [], []
    for e in app["inputs"]:
        members = tuple(sorted(t for t in e["ws_types"] if type_name(t)))
        if not members: continue
        if e["optional"]:
            skipped_optional.append(e["param_id"])
            continue
        ins.append((e, members))

    if not outs and not app["report_output"]:
        return None, "no_product"

    used = set()
    reqs, prods = [], []
    for e, members in ins:
        t = type_name(members[0]) if len(members) == 1 else unions_by_members[members]
        reqs.append((_var(e["param_id"], used), t, e))
    for e, members in outs:
        branches = [type_name(m) for m in members]
        prods.append((_var(e["param_id"], used), branches, e))
    if app["report_output"]:
        prods.append((_var("report", used), ["report"], None))

    return {"requires": reqs, "products": prods,
            "optional_not_modelled": skipped_optional}, "converted"


def _stub(app, plan) -> str:
    aid = app["app_id"]
    module = _module_of(app)
    cpus, mem, hrs = _resources(app)

    head = [BANNER, f'"""{aid} -- {app["name"] or ""}\n\n']
    provenance = [
        f"KBase app   : {aid} (spec {app['spec_version']}, {'active' if app['active'] else 'inactive'})",
        f"module      : {module or 'none -- legacy spec, no catalog module'}",
        f"git         : {app['git_url'] or '-'} @ {app['git_commit_hash'] or '-'}",
        f"service     : {app['service']['name'] or '-'}.{app['service']['method'] or '-'}",
    ]
    head.append("\n".join(provenance) + "\n")
    if app["subtitle"]:
        head.append("\n" + textwrap.fill(" ".join(app["subtitle"].split()), 78) + "\n")
    if plan.get("optional_not_modelled"):
        head.append("\n" + textwrap.fill(
            "Optional in KBase and therefore not a requirement here: "
            + ", ".join(plan["optional_not_modelled"]) + ".", 78) + "\n")
    if app["unresolved_types"]:
        head.append("\n" + textwrap.fill(
            "References workspace types the registry no longer serves: "
            + ", ".join(app["unresolved_types"])
            + ". They are still declared, from the app spec's own naming.", 78) + "\n")
    head.append(
        "\nStub: the model is the port, the body only touches its outputs. This does\n"
        "not run the KBase app. Regenerate with research/kbase/library/_generate.py.\n"
        '"""\n\n'
    )

    b = ["from metasmith.python_api import *\n\n"]
    b.append('lib   = TransformInstanceLibrary.ResolveParentLibrary(__file__)\n')
    b.append("model = Transform()\n")

    names = ["study", "sample"] + [v for v, _, _ in plan["requires"]]
    if module: names.append("env")
    names += [v for v, _, _ in plan["products"]]
    pad = max(len(n) for n in names)

    b.append(f'{"study":<{pad}} = model.AddRequirement(lib.GetType("kbase::study"))\n')
    b.append(f'{"sample":<{pad}} = model.AddRequirement(lib.GetType("kbase::sample"), parents={{study}})\n')
    for var, t, e in plan["requires"]:
        b.append(f'{var:<{pad}} = model.AddRequirement(lib.GetType("kbase::{t}"), parents={{sample}})\n')
    if module:
        b.append(f'{"env":<{pad}} = model.AddRequirement(lib.GetType("env::{env_type_name(module)}"))\n')

    for i, (var, branches, e) in enumerate(plan["products"]):
        if i and len(branches) == 1 and len(plan["products"][0][1]) > 1:
            pass
        if len(branches) == 1:
            b.append(f'{var:<{pad}} = model.AddProduct(lib.GetType("kbase::{branches[0]}"))\n')
        else:
            b.append(f"# {e['param_id']} is one of {len(branches)} types; each is its own product branch\n")
            for j, t in enumerate(branches):
                if j: b.append("model.NewProductGroup()\n")
                b.append(f'{var if not j else var + "_" + str(j + 1):<{pad}} = '
                         f'model.AddProduct(lib.GetType("kbase::{t}"))\n')

    first = plan["products"][0][0]
    b.append("\ndef protocol(context: ExecutionContext):\n")
    b.append(f"    made = {{{first}: context.Output({first})}}\n")
    for var, branches, _ in plan["products"][1:]:
        if len(branches) == 1:
            b.append(f"    made[{var}] = context.Output({var})\n")
    b.append("    for path in made.values():\n")
    b.append("        context.external_shell.Exec(f'touch {path.external}')\n")
    b.append("    return ExecutionResult(\n")
    b.append("        manifest=[{k: v.local for k, v in made.items()}],\n")
    b.append("        success=all(v.local.exists() for v in made.values()),\n")
    b.append("    )\n\n")

    group_by = plan["requires"][0][0] if plan["requires"] else "sample"
    b.append("TransformInstance(\n    protocol=protocol,\n    model=model,\n")
    b.append(f"    group_by={group_by},\n")
    b.append(f"    labels={['inactive'] if not app['active'] else []},\n")
    b.append("    resources=Resources(\n")
    b.append(f"        cpus={cpus},\n        memory=Size.GB({mem}),\n"
             f"        duration=Duration(hours={hrs}),\n    ),\n)\n")
    return "".join(head + b)


def stub_name(app) -> str:
    aid = app["app_id"]
    return re.sub(r"\W", "_", aid.replace("/", "__")) + ".py"


def write_transforms(apps, unions) -> tuple[int, list]:
    by_members = {members: name for name, (_tok, members) in unions.items()}
    XFORM_DIR.mkdir(parents=True, exist_ok=True)
    for stale in XFORM_DIR.glob("*.py"):
        stale.unlink()

    ledger, n = [], 0
    for app in apps:
        plan, why = plan_app(app, by_members)
        row = {
            "app_id": app["app_id"], "module": app["module"], "active": app["active"],
            "app_type": app["app_type"], "output_channel": app["output_channel"],
            "disposition": "converted" if plan else "dropped", "reason": why,
            "transform": None, "n_requires": None, "n_products": None,
        }
        if plan:
            fn = stub_name(app)
            (XFORM_DIR / fn).write_text(_stub(app, plan))
            row.update(transform=fn, n_requires=len(plan["requires"]),
                       n_products=len(plan["products"]),
                       optional_not_modelled=plan.get("optional_not_modelled") or [])
            n += 1
        ledger.append(row)
    return n, ledger


def lint_types() -> list[str]:
    import yaml
    problems = []
    raw = yaml.safe_load(TYPES_YML.read_text())["types"]

    sets = {}
    for name, body in raw.items():
        props = body["properties"]
        flat = set()
        if isinstance(props, dict):
            for k, v in props.items():
                if k == "_": flat.update(v if isinstance(v, list) else [v])
                else: flat.add(json.dumps({k: v}, separators=(",", ":"), sort_keys=True))
        else:
            flat.update(props)
        sets[name] = frozenset(flat)

    seen = {}
    for name, s in sets.items():
        if s in seen: problems.append(f"identical property sets: {seen[s]} == {name}")
        seen[s] = name

    unions = {n for n in raw if n.startswith("accepts_")}
    for a, sa in sets.items():
        for b, sb in sets.items():
            if a == b or b in unions or a in KEYSTONES or b in KEYSTONES: continue
            if sb < sa:
                problems.append(f"unintended subsumption: {a} satisfies {b}")

    # The check that matters: a union exists to be satisfied by its members, and
    # one stray property on it makes that silently false everywhere.
    apps, *_ = load()
    built, _tokens = build_unions(apps)
    for name, (_token, members) in built.items():
        for m in members:
            mn = type_name(m)
            if mn in sets and not (sets[name] <= sets[mn]):
                problems.append(f"union {name} is NOT satisfied by its member {mn}")
    return problems


def write_ledger(ledger, n_types, n_envs, n_transforms):
    (CATALOG / "ledger.jsonl").write_text("".join(json.dumps(r) + "\n" for r in ledger))

    census = json.loads((CATALOG / "census.json").read_text())
    total = census["apps"]["total"]
    assert len(ledger) == total, f"ledger has {len(ledger)} rows, census says {total} apps"
    by = collections.Counter(r["reason"] for r in ledger)
    assert sum(by.values()) == total, "dispositions do not sum to the census total"

    act = [r for r in ledger if r["active"]]
    act_conv = sum(1 for r in act if r["disposition"] == "converted")
    act_by = collections.Counter(r["reason"] for r in act)

    md = [
        "# Conversion ledger\n\n",
        "One row per app in the census. `ledger.jsonl` is the machine-readable form.\n",
        "The generator asserts this file's totals against `census.json` and fails when\n",
        "they disagree, so a silently skipped app cannot happen.\n\n",
        f"## Headline\n\n**Of the {len(act)} active KBase apps, {act_conv} became metasmith "
        f"transforms.**\nAcross all {total} apps in the catalog, {n_transforms} converted.\n\n",
        "## Active apps by disposition\n\n| reason | apps |\n|---|---|\n",
    ]
    for reason, cnt in act_by.most_common():
        md.append(f"| {reason} | {cnt} |\n")
    md.append(f"\n## All {total} apps by disposition\n\n| reason | apps |\n|---|---|\n")
    for reason, cnt in by.most_common():
        md.append(f"| {reason} | {cnt} |\n")
    md.append(
        "\n## What the reasons mean\n\n"
        "- **converted** — a stub transform exists under `library/transforms/kbase/`.\n"
        "- **no_product** — the app names nothing it creates: no typed output parameter and\n"
        "  no KBaseReport in its service output mapping. These are in-browser visualizations,\n"
        "  a staging exporter and an ACL update. A planner has nothing to target.\n"
        "- **polymorphic_output** — an output parameter accepting more than "
        f"{MAX_OUTPUT_BRANCHES} workspace\n  types. These are generic object shufflers, not workflow steps.\n"
        f"\n## Library\n\n{n_types} data types, {n_envs} tool environments, {n_transforms} transforms.\n"
    )
    (CATALOG / "ledger.md").write_text("".join(md))
    return act_conv, len(act), by


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lint", action="store_true", help="check the emitted types only")
    a = ap.parse_args()

    apps, types, modules, images = load()
    if a.lint:
        for p in lint_types(): print("  LINT:", p)
        print("lint done")
        return

    n_types, unions, _tokens = write_types(apps, types)
    n_envs = write_envs(apps, modules, images)
    n_transforms, ledger = write_transforms(apps, unions)
    act_conv, act_total, by = write_ledger(ledger, n_types, n_envs, n_transforms)

    print(f"types      : {n_types} ({len(unions)} unions)")
    print(f"envs       : {n_envs}")
    print(f"transforms : {n_transforms}")
    print(f"ledger     : {len(ledger)} rows, reconciles with census")
    print(f"HEADLINE   : {act_conv} of {act_total} active apps converted")
    for r, c in by.most_common(): print(f"   {r:22s} {c}")
    problems = lint_types()
    for p in problems[:20]: print("  LINT:", p)
    print(f"lint       : {len(problems)} problems")


if __name__ == "__main__":
    main()
